"""LLM analysis stage; falls back to deterministic explanations when no key is configured."""
import json
import os
from typing import Dict, List
try:
    import anthropic
    _client = anthropic.Anthropic(api_key=os.environ.get("ANTHROPIC_API_KEY", ""))
except Exception:
    _client = None
MODEL = os.environ.get("ANTHROPIC_MODEL", "claude-sonnet-4-6")
def _has_llm(): return _client is not None and bool(os.environ.get("ANTHROPIC_API_KEY"))
def explain_issues_with_llm(files: Dict[str, str], findings: List[dict]) -> List[dict]:
    results=[]
    for finding in findings:
        context=_extract_context(files.get(finding["fileName"], ""), finding.get("lineNumber", 1))
        enriched=_call_llm_explain(finding, context) if _has_llm() else _fallback_explain(finding)
        results.append({"fileName":finding["fileName"],"lineNumber":finding.get("lineNumber"),"category":finding["category"],**enriched})
    return results
def _extract_context(content: str, lineno: int, window: int=5) -> str:
    lines=content.splitlines(); return "\n".join(lines[max(0,(lineno or 1)-window-1):min(len(lines),(lineno or 1)+window)])
def _call_llm_explain(finding: dict, context: str) -> dict:
    prompt=f'''You are a senior code reviewer. Respond ONLY with JSON matching: {{"severity":"LOW|MEDIUM|HIGH|CRITICAL","description":"why this matters","suggestion":"concrete fix","correctedCode":"fixed code or null","complexity":"e.g. O(n)","confidence":0.0}}
Category: {finding['category']}\nHint: {finding.get('hint','')}\nCode:\n{context}'''
    try:
        msg=_client.messages.create(model=MODEL,max_tokens=600,messages=[{"role":"user","content":prompt}])
        return json.loads("".join(b.text for b in msg.content if hasattr(b,"text")))
    except Exception: return _fallback_explain(finding)
_SEVERITY={"SECURITY":"HIGH","BUG":"MEDIUM","PERFORMANCE":"MEDIUM","CODE_SMELL":"LOW","DOCUMENTATION":"LOW","MAINTAINABILITY":"LOW"}
def _fallback_explain(finding: dict) -> dict:
    cat=finding["category"]; hint=finding.get("hint","Potential issue detected by static analysis.")
    return {"severity":_SEVERITY.get(cat,"MEDIUM"),"description":hint,"suggestion":_suggestion(cat,hint),"correctedCode":None,"complexity":"O(n)" if cat=="PERFORMANCE" else None,"confidence":0.7}
def _suggestion(category: str, hint: str) -> str:
    h=hint.lower()
    if "division" in h or "modulo" in h: return "Check that the denominator is nonzero before dividing."
    if "null" in h: return "Add a null check or use a null-safe accessor before dereferencing."
    if "credential" in h: return "Move secrets to environment variables or a secret manager."
    if "sql injection" in h: return "Use parameterized queries instead of string concatenation."
    if "nested loop" in h: return "Consider a more efficient algorithm or data structure."
    if "debug print" in h: return "Remove debug output or replace it with structured logging."
    if "empty catch" in h: return "Log or explicitly handle the exception."
    if "todo" in h or "fixme" in h: return "Resolve this TODO/FIXME or track it as an issue."
    if "eval" in h or "exec" in h: return "Avoid dynamic execution on untrusted input."
    if "syntax error" in h: return "Fix the syntax error before running this code."
    if "mutable default" in h: return "Use None and initialize the mutable value inside the function."
    return {"SECURITY":"Validate input and prevent injection or data exposure.","BUG":"Handle edge cases and validate values before use.","PERFORMANCE":"Consider a more efficient algorithm or data structure.","CODE_SMELL":"Refactor for clarity and explicit error handling.","DOCUMENTATION":"Resolve the TODO or document the intent.","MAINTAINABILITY":"Extract a smaller, well-named function."}.get(category,"Review this finding manually.")
def explain_single(issue: dict) -> dict: return _call_llm_explain(issue,issue.get("snippet","")) if _has_llm() else _fallback_explain(issue)
def optimize_code(code: str, language: str) -> dict:
    if not _has_llm(): return {"optimizedCode":code,"notes":"LLM not configured; returning original code unchanged."}
    try:
        msg=_client.messages.create(model=MODEL,max_tokens=1500,messages=[{"role":"user","content":f"Optimize this {language} code. Return only code:\n{code}"}])
        return {"optimizedCode":"".join(b.text for b in msg.content if hasattr(b,"text")),"notes":"Generated by LLM."}
    except Exception: return {"optimizedCode":code,"notes":"LLM call failed."}
def generate_tests(code: str, language: str) -> dict:
    if not _has_llm(): return {"tests":"// LLM not configured","notes":"Set ANTHROPIC_API_KEY to enable test generation."}
    try:
        msg=_client.messages.create(model=MODEL,max_tokens=1500,messages=[{"role":"user","content":f"Write unit tests for this {language} code. Return only test code:\n{code}"}])
        return {"tests":"".join(b.text for b in msg.content if hasattr(b,"text")),"notes":"Generated by LLM."}
    except Exception: return {"tests":"","notes":"LLM call failed."}
